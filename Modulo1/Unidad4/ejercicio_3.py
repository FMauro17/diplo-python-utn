"""
Ejercicio 3 - Dificultad media
Crear una funcion lambda equivalente a la funcion sumar,
que toma dos valores y devuelve su suma.
"""

# Defina una lambda que recibe dos valores y devuelve su suma
sumar = lambda valor1, valor2: valor1 + valor2

# Llama a lambda con dos numeros y muestra el resultado
print(sumar(5, 3))